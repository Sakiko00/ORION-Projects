/** 直接造一个 t()。App 根组件用它（它自己不在 Provider 里，拿不到 useT） */
export function makeT(lang: Lang): (key: string, vars?: Record<string, string | number>) => string {
  const dict = lang === 'en' ? EN : ZH
  return (key: string, vars?: Record<string, string | number>): string => {
    /* 找不到就回退中文，最后才回退 key —— 漏词时界面还能看，只是没翻 */
    let s = dict[key] ?? ZH[key] ?? key
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
    return s
  }
}

const I18nCtx = createContext<(key: string, vars?: Record<string, string | number>) => string>(
  () => ''
)

export function I18nProvider({ lang, children }: { lang: Lang; children: ReactNode }) {
  const t = useMemo(() => makeT(lang), [lang])
  return <I18nCtx.Provider value={t}>{children}</I18nCtx.Provider>
}

export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  return useContext(I18nCtx)
}
